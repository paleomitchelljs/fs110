#!/usr/bin/env python3
"""Write js/dims.js: pixel size of every picture in img/, so content.js can say F('name.jpg', caption)."""
import os, json
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); IMG = os.path.join(HERE, '..', 'img')
d = {f: list(Image.open(os.path.join(IMG, f)).size) for f in sorted(os.listdir(IMG)) if f.lower().endswith(('.jpg', '.png'))}
open(os.path.join(HERE, '..', 'js', 'dims.js'), 'w').write('/* generated by tools/dims.py */\nwindow.DIMS = ' + json.dumps(d) + ';\n')
print(len(d), 'pictures')
