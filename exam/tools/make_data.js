// Turns example_students.csv into js/data.js. Run from anywhere: node exam/tools/make_data.js
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..');
const rows = fs.readFileSync(path.join(dir, 'example_students.csv'), 'utf8').trim().split(/\r?\n/).map((l) => l.split(','));
const head = rows.shift();
const col = (n) => head.indexOf(n);
const ids = head.slice(col('uniform01'));          // every column after class_avg is one student
// exam_question_traits.csv: one row per question of the 50, with quoted fields. Questions missing from the students file are skipped.
const cells = (l) => (l.match(/("([^"]|"")*"|[^,]*)(,|$)/g) || []).map((c) => c.replace(/,$/, '').replace(/^"|"$/g, '').replace(/""/g, '"'));
const traitRows = fs.readFileSync(path.join(dir, 'exam_question_traits.csv'), 'utf8').trim().split(/\r?\n/).slice(1).map(cells);
const trait = {};
traitRows.forEach((r) => { trait[+r[0]] = { bloom: r[1], crit: r[2] !== 'None', words: +r[4], rl: +r[3].match(/\d+/)[0] }; });
const q = rows.map((r) => {
  const n = +r[col('question')];
  if (!trait[n]) throw new Error('no traits for question ' + n);
  return Object.assign({ n, ch: +r[col('chapter')], avg: +r[col('class_avg')] }, trait[n]);
});
// Students are shown as A, B, C, D in file order. The file's own names say which is which, so they stay out of the page.
const students = ids.map((id, i) => ({ id: 'ABCD'[i], v: rows.map((r) => +r[col(id)]) }));
const out = '/* Generated by tools/make_data.js from example_students.csv. q: question number, chapter, share of the class who got it right, bloom level, critical word present, word count, reading grade. v: 1 right, 0 wrong. */\n' +
  'window.EXAM = ' + JSON.stringify({ q, students }) + ';\n';
fs.writeFileSync(path.join(dir, 'js', 'data.js'), out);
console.log(q.length + ' questions, ' + students.length + ' students');
